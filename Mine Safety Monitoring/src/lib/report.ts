import { prettyName, type Dataset, type DatasetInsights } from "@/lib/dataset";
import {
  SAFETY_STATUS_LABEL,
  type SafetyAssessment,
} from "@/lib/safety/assess";
import { VERIFICATION_LABEL } from "@/lib/safety/config";
import {
  RESULT_TEXT,
  formatReading,
  formatThreshold,
} from "@/lib/safety/format";

export interface AnalysisRecord {
  insights: DatasetInsights;
  model: string;
  analysedAt: string; // ISO timestamp
  durationMs?: number;
  /** "ollama" (local app) or "webllm" (in the browser). */
  provider?: string;
  /** "code" when the headline/summary were written from statistics instead of the model. */
  summarySource?: "model" | "code";
}

export const AI_DISCLAIMER =
  "Generated by a local language model from statistics computed in this app. " +
  "It is a statistical read of the uploaded file, not a certified safety assessment.";

/** Markdown shift report for download. Built entirely in the browser. */
export function buildMarkdownReport(
  dataset: Dataset,
  analysis: AnalysisRecord,
  assessment?: SafetyAssessment,
): string {
  const { insights } = analysis;
  const safetyLines: string[] = [];
  if (assessment) {
    safetyLines.push(
      `## Safety status: ${SAFETY_STATUS_LABEL[assessment.status]}`,
      "",
      `_Rule-based classification. Newest reading: ${assessment.latestTimestamp ?? "—"}${assessment.isStale ? " (STALE)" : ""}. Rules: ${assessment.configName}._`,
      "",
      ...assessment.reasons.map((r) => `- ${r}`),
      "",
    );
    if (assessment.dataQuality.length) {
      safetyLines.push(
        "**Data-quality warnings:**",
        "",
        ...assessment.dataQuality.map((q) => `- ${q.message}`),
        "",
      );
    }
    const shown = assessment.evaluations.filter(
      (e) => e.result !== "not_evaluated",
    );
    if (shown.length) {
      safetyLines.push(
        "| Rule | Parameter | Result | Latest | 1-hour moving average | Worst (window) | Warning | Critical | Status | Source |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
        ...shown.map(
          (e) =>
            `| ${e.ruleId} | ${e.parameter} | ${RESULT_TEXT[e.result]} | ${formatReading(e.latestValue, e.unit)} | ${formatReading(e.movingAvg1h, e.unit)} | ${formatReading(e.worstValue, e.unit)} | ${formatThreshold(e, "warning")} | ${formatThreshold(e, "critical")} | ${VERIFICATION_LABEL[e.verificationStatus]} | ${e.sourceClause.replace(/\|/g, "/")} |`,
        ),
        "",
      );
    }
    const notChecked = assessment.evaluations.filter(
      (e) => e.result === "not_evaluated",
    );
    if (notChecked.length) {
      safetyLines.push(
        "**Rules not checked:**",
        "",
        ...notChecked.map(
          (e) => `- ${e.ruleId} (${e.parameter}): ${e.notEvaluatedReason}`,
        ),
        "",
      );
    }
    if (insights.safety?.explanation) {
      safetyLines.push(
        `**AI explanation:** ${insights.safety.explanation}`,
        "",
      );
      if (insights.safety.needsReview)
        safetyLines.push(
          `> ⚠ ${insights.safety.reviewReason ?? "The AI wording needs review."}`,
          "",
        );
    }
    if (assessment.nextActions.length) {
      safetyLines.push(
        "**Rule-based next actions:**",
        "",
        ...assessment.nextActions.map((a) => `- ${a}`),
        "",
      );
    }
  }
  const lines = [
    `# ${insights.headline}`,
    "",
    `- **File:** ${dataset.name}`,
    `- **Rows:** ${dataset.rowCount}`,
    `- **Model:** ${analysis.model} (ran on this device)`,
    `- **Analysed:** ${new Date(analysis.analysedAt).toLocaleString()}`,
    "",
    ...safetyLines,
    "## Summary",
    "",
    insights.summary,
    "",
    "## Findings",
    "",
    ...insights.findings.map(
      (f) =>
        `- **${prettyName(f.parameter)}** (${f.severity.toUpperCase()}): ${f.observation}` +
        (f.interpretation
          ? `\n  - _Possible explanation:_ ${f.interpretation}`
          : ""),
    ),
    "",
    "## Recommended actions",
    "",
    ...insights.recommendations.map((r, i) => `${i + 1}. ${r}`),
    "",
    "---",
    "",
    "_Finding facts and severities are computed by the app. Severity is statistical: critical = a value at |z| ≥ 4 or a 50%+ change; watch = a |z| ≥ 3 outlier, a 10%+ change or 10%+ missing values._",
    "",
    `_${AI_DISCLAIMER}_`,
    "",
  ];
  return lines.join("\n");
}

/** Trigger a browser download of text content. The user picks where it goes. */
export function downloadText(
  filename: string,
  text: string,
  type = "text/markdown",
) {
  const blob = new Blob([text], { type: `${type};charset=utf-8` });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

export function reportFileName(datasetName: string): string {
  const base =
    datasetName
      .replace(/\.[^.]+$/, "")
      .replace(/[^a-zA-Z0-9._-]+/g, "_")
      .slice(0, 80) || "dataset";
  return `${base}-shift-report.md`;
}
